function LyricBlock({ section }) {
  return (
    <section className="mt-5 first:mt-0">
      {section.title && (
        <h4 className="mb-1 text-[16px] font-bold italic text-[#7b371d]">
          {section.title}
        </h4>
      )}
      <div className={`${section.emphasis ? 'font-bold' : ''} space-y-0.5 text-[16px] leading-snug text-[#170d08]`}>
        {section.lines.map((line, index) => (
          <p key={`${line}-${index}`}>{line}</p>
        ))}
      </div>
      {section.finale && (
        <div className="mt-7 space-y-1 text-center text-[22px] font-bold uppercase leading-tight tracking-[0.08em] text-[#170d08] md:text-[26px]">
          {section.finale.map((line) => (
            <p key={line}>{line}</p>
          ))}
        </div>
      )}
    </section>
  );
}

